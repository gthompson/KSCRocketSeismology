"""Recover raw counts for 1R.B29.00.DHZ over the Artemis II launch window.

In both the master SDS (/Volumes/KSCGTdownld/SDS) and the haldata copy, the
1R.B29.00.DHZ day files for 2026 days 082-093 contain only zero bytes. The Box
file artemis2_launch_sds.mseed (written 2026-04-08) holds the launch window
(2026-04-01 22:05:12 to 23:20:12 UTC) as raw counts divided by 3e8. Multiplying
back gives integers; for intact channels (1R.B01.00.DHZ, 1R.B29.00.DH1) the
result matches the SDS counts sample for sample.

This script writes the recovered counts to a SEPARATE SDS-style folder for
inspection. It never touches the master SDS. The recovered file keeps the Centaur
spelling DHZ (as do the zero-filled archive days); ksclib reads it as the SEED code CHZ.
The intact check channels may be spelled D?? or, after the archive rename, C??.

    python restore_B29_DHZ.py
"""
from pathlib import Path

import numpy as np
from obspy import read

SOURCE = (Path("~").expanduser() / "Library/CloudStorage/Box-Box/thompsong/3_Project_Documents"
          / "NASAprojects/201602_Rocket_Seismology/writing/Artemis2/artemis2_launch_sds.mseed")
SCALE = 3e8                      # counts = value * SCALE
MASTER_SDS = Path("/Volumes/KSCGTdownld/SDS")
CHECKS = ["1R.B01.00.DHZ", "1R.B29.00.DH1"]   # intact channels, day 2026-091 (as named in SOURCE)
TARGET_ID = "1R.B29.00.DHZ"
OUT_ROOT = Path("/Volumes/KSCGTdownld/20260403_service/30_qc/B29_DHZ_restored")


def master_day_file(seed_id, year=2026, jday=91):
    """Master SDS day file for a Centaur channel, spelled D?? or (after the rename) C??."""
    net, sta, loc, cha = seed_id.split(".")
    for c in (cha, "C" + cha[1:]):
        path = MASTER_SDS / str(year) / net / sta / f"{c}.D" / f"{net}.{sta}.{loc}.{c}.D.{year}.{jday:03d}"
        if path.exists():
            return path
    raise FileNotFoundError(f"no master SDS day file for {seed_id} ({year}.{jday:03d})")


def to_counts(tr):
    x = tr.data.astype(np.float64) * SCALE
    resid = np.abs(x - np.round(x)).max()
    if resid > 1e-6:
        raise ValueError(f"{tr.id}: not integer counts after x{SCALE:g} (max residual {resid:.2e})")
    return np.round(x).astype(np.int32), resid


def main():
    st = read(str(SOURCE))

    # 1. The scaling must reproduce intact channels exactly.
    for sid in CHECKS:
        tr = st.select(id=sid)[0]
        counts, _ = to_counts(tr)
        ref = read(str(master_day_file(sid)), starttime=tr.stats.starttime, endtime=tr.stats.endtime).merge()[0]
        n = min(len(counts), ref.stats.npts)
        same = ref.stats.starttime == tr.stats.starttime and np.array_equal(counts[:n], ref.data[:n])
        print(f"check {sid}: {n} samples, exact match = {same}")
        if not same:
            raise SystemExit("Scaling check failed; nothing written.")

    # 2. Recover the damaged channel.
    tr = st.select(id=TARGET_ID)[0].copy()
    tr.data, resid = to_counts(tr)
    s = tr.stats
    out_dir = OUT_ROOT / "SDS" / str(s.starttime.year) / s.network / s.station / f"{s.channel}.D"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{TARGET_ID}.D.{s.starttime.year}.{s.starttime.julday:03d}"
    if out.exists():
        raise SystemExit(f"{out} exists; remove it first to regenerate.")
    tr.write(str(out), format="MSEED", encoding="STEIM1", reclen=512, byteorder=">")

    # 3. Read back and compare.
    back = read(str(out))[0]
    ok = back.stats.starttime == s.starttime and np.array_equal(back.data, tr.data)
    print(f"wrote {out}")
    print(f"  {back.id} {back.stats.starttime} - {back.stats.endtime}  {back.stats.npts} samples "
          f"@ {back.stats.sampling_rate} Hz, int counts {back.data.min()}..{back.data.max()}, "
          f"max rounding residual {resid:.1e}, read-back identical = {ok}")

    (OUT_ROOT / "README.txt").write_text(
        f"Recovered {TARGET_ID} raw counts, {s.starttime} to {s.endtime} (launch window only).\n"
        f"Source: {SOURCE} (values = counts / {SCALE:g}).\n"
        f"Scaling verified sample-for-sample against intact SDS channels: {', '.join(CHECKS)}.\n"
        "The master SDS and haldata copies of 1R.B29.00.DHZ days 082-093 are zero-filled;\n"
        "data outside this window are not recovered here. Generated by\n"
        "KSCRocketSeismoHydrology/09_artemis2_paper/restore_B29_DHZ.py. Not merged into the master SDS.\n")


if __name__ == "__main__":
    main()
