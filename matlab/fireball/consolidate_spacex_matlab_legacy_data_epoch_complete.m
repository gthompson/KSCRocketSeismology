    nNPhasePicks(eventIndex) = sum(lower(strip(rows.phase)) == "n");
    nInfrasoundChannelPicks(eventIndex) = ...
        sum(rows.isInfrasoundChannel);
    nSeismicChannelPicks(eventIndex) = ...
        sum(rows.isSeismicChannel);
end

