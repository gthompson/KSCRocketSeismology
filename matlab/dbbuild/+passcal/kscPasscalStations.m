function s = makeStation(name, description, location, lat, lon, orientation_geo, ...
    ondate, offdate, samplerate, sensor, sensorSN, datalogger, elev, depth, notes)

s.name = name;
s.description = description;
s.location = location;
s.channels = ['EHZ'; 'EH1'; 'EH2'];
s.lat = lat;
s.lon = lon;
s.elev = elev;
s.orientationFromGeographicNorth = orientation_geo;
s.ondate = ondate;
s.offdate = offdate;
s.samplerate = samplerate;
s.sensor = sensor;
s.sensorSN = sensorSN;
s.datalogger = datalogger;
s.burialdepth = depth;
s.notes = notes;
end
